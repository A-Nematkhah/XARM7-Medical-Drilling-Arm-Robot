"""Shared driver contracts for sim and real robot.

Live xArm motion must run on the controller — never port `Robot.servo_step`
/ `mj_jacSite` as the hardware control loop. The task talks only through
`ArmDriver.move_to_pose` / `move_joints` / planning helpers below.
"""
from __future__ import annotations

from typing import Protocol, runtime_checkable

import numpy as np


@runtime_checkable
class ArmDriver(Protocol):
    """Controller-facing arm API. Sim implements this with MuJoCo; real uses the xArm SDK."""

    max_track_err: float
    callbacks: list
    rest_q: np.ndarray
    qadr: np.ndarray  # indices into the backend q vector (sim: qpos; real: unused)

    def wait(self, t: float) -> None: ...
    def move_joints(self, q_goal, T: float = 2.0) -> None: ...
    def move_to_pose(self, p_goal, R_goal, T: float = 2.0, settle: float = 0.3,
                    gain: float = 0.6, vmax=None): ...
    def move_along(self, direction, distance_m, R_hold, T: float = 1.0, speed=None, settle: float = 0.05): ...
    def site_pose(self) -> tuple[np.ndarray, np.ndarray]: ...
    def get_q(self) -> np.ndarray: ...
    def limit_margin(self, q) -> float: ...
    def plan_path_ik(self, waypoints, R, min_margin: float = 0.2, max_jump: float = 1.0): ...
    def move_joint_path(self, chain, T_first: float = 3.0, T_step: float = 0.8): ...
    def ik_solutions(self, p_goal, R_goal, n_random: int = 16): ...
    def goto_pose_joint_space(self, p_goal, R_goal, T: float = 2.5, seed=None): ...


@runtime_checkable
class HandDriver(Protocol):
    OPEN: list

    def set_angles(self, angles, speed=None) -> None: ...
    def get_angles(self): ...
    def get_forces(self): ...


@runtime_checkable
class WristCamera(Protocol):
    @property
    def K(self) -> np.ndarray: ...

    def capture(self): ...
    def pose(self) -> tuple[np.ndarray, np.ndarray]: ...
    def deproject(self, us, vs, zs, cam_pose=None) -> np.ndarray: ...
    def project(self, P, cam_pose=None): ...


@runtime_checkable
class WristLidarDriver(Protocol):
    """360° coarse locator on the hand. Not a pierce sensor."""

    def pose(self) -> tuple[np.ndarray, np.ndarray]: ...
    def scan(self): ...
    def locate(self, scan=None): ...


# Older names from the column-camera / column-lidar layout.
BaseCamera = WristCamera
ColumnLidarDriver = WristLidarDriver
